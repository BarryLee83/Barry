export const STRINGS = { 'zh-CN': ZH, en: EN };

let lang = 'zh-CN';

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = LANGS.includes(next) ? next : 'zh-CN';
  document.documentElement.lang = lang;
  return lang;
}

export function t(key, params) {
  const table = STRINGS[lang] || ZH;
  let text = table[key];
  if (text == null) text = ZH[key];
  if (text == null) return key;
  if (params) {
    text = text.replace(/\{(\w+)\}/g, (m, name) =>
      params[name] === undefined || params[name] === null ? m : String(params[name])
    );
  }
  return text;
}

export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
}
